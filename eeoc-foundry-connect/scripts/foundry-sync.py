#!/usr/bin/env python3
"""Configure OMP for EEOC Azure AI Foundry using Microsoft Entra ID.

This script replaces legacy static API-key authentication with an Azure CLI
command-backed bearer token and writes the actual Foundry account deployments
into ~/.omp/agent/models.yml.

Default EEOC DEV endpoint:
    https://aif-eeoc-daes-dev.services.ai.azure.com

Typical usage:
    python foundry-sync.py

Override endpoint when needed:
    python foundry-sync.py --endpoint https://<resource>.services.ai.azure.com

Requirements:
    - Python 3
    - Azure CLI (`az`)
    - `az login` completed
    - Access to the target Azure AI Foundry account

No Foundry API key or Entra access token is stored on disk.
"""

