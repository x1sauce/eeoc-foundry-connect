def run_az(args: list[str], *, timeout: int = 45) -> str:
    """Run Azure CLI and return trimmed stdout or exit with a useful error."""
    command = ["az", *args]
    try:
        result = subprocess.run(
            command,
            check=True,
            capture_output=True,
            text=True,
            timeout=timeout,
            shell=(os.name == "nt"),
        )
    except FileNotFoundError:
        sys.exit("Azure CLI (`az`) was not found. Install Azure CLI, run `az login`, and retry.")
    except subprocess.TimeoutExpired:
        sys.exit(f"Azure CLI timed out: {' '.join(command)}")
    except subprocess.CalledProcessError as exc:
        detail = (exc.stderr or exc.stdout or "").strip()
        sys.exit(f"Azure CLI command failed:\n  {' '.join(command)}\n\n{detail}")
    return result.stdout.strip()


def read_env_file() -> dict[str, str]:
    if not ENV_FILE.is_file():
        return {}
    values: dict[str, str] = {}
    for raw in ENV_FILE.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        name, _, value = line.partition("=")
        values[name.strip()] = value.strip().strip("'\"")
    return values


def write_env_file(values: dict[str, str]) -> None:
    AGENT_DIR.mkdir(parents=True, exist_ok=True)
    body = [
        "# Azure AI Foundry configuration for OMP's `foundry` provider.",
        "# Authentication uses Microsoft Entra ID through Azure CLI.",
        "# No Foundry API key or Entra access token is stored here.",
    ]
    body.extend(f"{name}={values[name]}" for name in sorted(values))
    ENV_FILE.write_text("\n".join(body) + "\n", encoding="utf-8")
    try:
        ENV_FILE.chmod(0o600)
    except OSError:
        pass


def normalize_endpoint(value: str) -> str:
    endpoint = value.strip().rstrip("/")
    parsed = urlparse(endpoint)
    if parsed.scheme.lower() != "https" or not parsed.hostname:
        sys.exit(f"Foundry endpoint must be an HTTPS URL (got: {value!r})")
    if not parsed.hostname.endswith((".services.ai.azure.com", ".openai.azure.com")):
        sys.exit(
            "Foundry endpoint must use a supported Azure AI host "
            "(.services.ai.azure.com or .openai.azure.com)."
        )
    return endpoint


def infer_account_name(endpoint: str) -> str:
    hostname = urlparse(endpoint).hostname or ""
    account = hostname.split(".", 1)[0].strip()
    if not account:
        sys.exit(f"Could not infer Azure AI account name from endpoint: {endpoint}")
    return account


def ensure_login_and_subscription(subscription: str | None) -> tuple[str, str, str]:
    account_json = run_az(["account", "show", "--output", "json"])
    try:
        account = json.loads(account_json)
    except json.JSONDecodeError as exc:
        sys.exit(f"Could not parse `az account show`: {exc}")

    if subscription:
        current_name = str(account.get("name") or "")
        current_id = str(account.get("id") or "")
        if subscription not in {current_name, current_id}:
            print(f"switching Azure subscription to: {subscription}")
            run_az(["account", "set", "--subscription", subscription])
            account_json = run_az(["account", "show", "--output", "json"])
            account = json.loads(account_json)

    name = str(account.get("name") or "")
    tenant = str(account.get("tenantId") or "")
    user_obj = account.get("user") if isinstance(account.get("user"), dict) else {}
    user = str(user_obj.get("name") or "")
    print(f"Azure subscription: {name or '(unknown)'}")
    print(f"Azure tenant:       {tenant or '(unknown)'}")
    print(f"Azure identity:     {user or '(unknown)'}")
    return name, tenant, user


def validate_foundry_token() -> None:
    token = run_az(
        [
            "account",
            "get-access-token",
            "--resource",
            FOUNDRY_RESOURCE,
            "--query",
            "accessToken",
            "--output",
            "tsv",
        ]
    )
    if not token:
        sys.exit("Azure CLI returned an empty Foundry access token.")
    print("Foundry Entra token: OK")


def discover_resource_group(account_name: str, explicit: str | None) -> str:
    if explicit:
        return explicit
    query = f"[?name=='{account_name}'].resourceGroup | [0]"
    group = run_az(["cognitiveservices", "account", "list", "--query", query, "--output", "tsv"])
    if not group:
        sys.exit(
            f"Could not find Cognitive Services account '{account_name}' in the active subscription.\n"
            "Pass --resource-group explicitly or verify `az account show`."
        )
    print(f"resource group:      {group}")
    return group


def list_deployments(account_name: str, resource_group: str) -> list[dict]:
    raw = run_az(
        [
            "cognitiveservices",
            "account",
            "deployment",
            "list",
            "--name",
            account_name,
            "--resource-group",
            resource_group,
            "--output",
            "json",
        ],
        timeout=60,
    )
    try:
        payload = json.loads(raw)
    except json.JSONDecodeError as exc:
        sys.exit(f"Could not parse Azure deployment list JSON: {exc}")
    if not isinstance(payload, list):
        sys.exit("Azure CLI deployment list did not return a JSON array.")

    deployments: list[dict] = []
    for dep in payload:
        if not isinstance(dep, dict):
            continue
        props = dep.get("properties") if isinstance(dep.get("properties"), dict) else {}
        state = str(props.get("provisioningState") or dep.get("provisioningState") or "").lower()
        # Keep rows when state is absent; otherwise require succeeded.
        if state and state != "succeeded":
            continue
        name = str(dep.get("name") or "").strip()
        if name:
            deployments.append(dep)

    if not deployments:
        sys.exit(
            "No active Foundry deployments were returned for this account.\n"
            f"Account: {account_name}\nResource group: {resource_group}"
        )
    return deployments


def meta_for(model_name: str, deployment_name: str) -> tuple[int, int, bool, bool]:
    candidates = (model_name.lower(), deployment_name.lower())
    for prefixes, meta in FAMILIES:
        if any(candidate.startswith(prefix) for candidate in candidates for prefix in prefixes):
            return meta
    return DEFAULT_META


def deployment_model_name(dep: dict) -> str:
    props = dep.get("properties") if isinstance(dep.get("properties"), dict) else {}
    model = props.get("model") if isinstance(props.get("model"), dict) else {}
    return str(model.get("name") or dep.get("name") or "").strip()


def build_provider(endpoint: str, deployments: list[dict]) -> dict:
    models: list[dict] = []
    for dep in sorted(deployments, key=lambda item: str(item.get("name", "")).lower()):
        deployment_name = str(dep.get("name") or "").strip()
        if not deployment_name:
            continue
        model_name = deployment_model_name(dep) or deployment_name
        context_window, max_tokens, reasoning, vision = meta_for(model_name, deployment_name)
        entry: dict[str, object] = {
            "id": deployment_name,
            "name": f"{model_name} (Foundry)",
            "contextWindow": context_window,
            "maxTokens": max_tokens,
            "input": ["text", "image"] if vision else ["text"],
        }
        if reasoning:
            entry["reasoning"] = True
        models.append(entry)

    return {
        "baseUrl": f"{endpoint.rstrip('/')}/openai/v1",
        "api": "openai-responses",
        "apiKey": OMP_TOKEN_COMMAND,
        "authHeader": True,
        "compat": {
            "strictResponsesPairing": True,
            "supportsDeveloperRole": True,
            "supportsStore": False,
        },
        "models": models,
    }


def emit_scalar(value: object) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    text = str(value)
    if text != text.strip() or not text or text[0] in "&*?|-<>=!%@`\"'{}[]# ,":
        return json.dumps(text)
    return text


def emit_yaml(node: object, indent: int = 0) -> list[str]:
    pad = "  " * indent
    lines: list[str] = []
    if isinstance(node, dict):
        for key, value in node.items():
            if isinstance(value, (dict, list)) and value:
                lines.append(f"{pad}{key}:")
                lines += emit_yaml(value, indent + 1)
            elif isinstance(value, dict):
                lines.append(f"{pad}{key}: {{}}")
            elif isinstance(value, list):
                lines.append(f"{pad}{key}: []")
            else:
                lines.append(f"{pad}{key}: {emit_scalar(value)}")
    elif isinstance(node, list):
        for item in node:
            if isinstance(item, dict) and item:
                nested = emit_yaml(item, indent + 1)
                lines.append(f"{pad}- {nested[0].lstrip()}")
                lines += nested[1:]
            else:
                lines.append(f"{pad}- {emit_scalar(item)}")
    return lines


def merge_document(provider: dict) -> dict:
    document: dict = {"providers": {}}
    if MODELS_YML.is_file():
        text = MODELS_YML.read_text(encoding="utf-8")
        if yaml is not None:
            existing = yaml.safe_load(text) or {}
            if isinstance(existing, dict):
                document = existing
                document.setdefault("providers", {})
        elif text.startswith("# generated by"):
            # This file was already generated by one of the sync scripts. Without
            # PyYAML we can safely replace it because its contents are derived.
            document = {"providers": {}}
        else:
            sys.exit(
                f"{MODELS_YML} contains user-managed configuration and PyYAML is not installed.\n"
                "Install PyYAML (`python -m pip install pyyaml`) so this script can preserve other providers."
            )

    providers = document.setdefault("providers", {})
    if not isinstance(providers, dict):
        sys.exit(f"Invalid `providers` block in {MODELS_YML}")
    providers[PROVIDER_ID] = provider
    return document


def backup_models_file() -> Path | None:
    if not MODELS_YML.is_file():
        return None
    stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    backup = MODELS_YML.with_name(f"models.yml.bak-{stamp}")
    shutil.copy2(MODELS_YML, backup)
    return backup


def write_models(document: dict, *, dry_run: bool) -> None:
    if yaml is not None:
        body = yaml.safe_dump(document, sort_keys=False, width=120)
    else:
        body = "\n".join(emit_yaml(document)) + "\n"
    rendered = f"{SENTINEL}\n{body}"

    if dry_run:
        print("\n--- dry-run models.yml ---")
        print(rendered)
        return

    AGENT_DIR.mkdir(parents=True, exist_ok=True)
    backup = backup_models_file()
    MODELS_YML.write_text(rendered, encoding="utf-8")
    if backup:
        print(f"backup:              {backup}")


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Configure OMP Foundry models with Azure CLI / Entra bearer authentication."
    )
    parser.add_argument(
        "--endpoint",
        help=f"Foundry endpoint (default: saved endpoint or {DEFAULT_ENDPOINT})",
    )
    parser.add_argument(
        "--subscription",
        default=os.environ.get("AZURE_SUBSCRIPTION") or DEFAULT_SUBSCRIPTION,
        help=f"Azure subscription name/ID (default: {DEFAULT_SUBSCRIPTION})",
    )
    parser.add_argument("--resource-group", help="Azure resource group; auto-discovered when omitted")
    parser.add_argument("--account-name", help="Foundry/Cognitive Services account name; inferred from endpoint")
    parser.add_argument("--dry-run", action="store_true", help="validate and print generated YAML without writing files")
    args = parser.parse_args()

    env_values = read_env_file()
    endpoint = normalize_endpoint(
        args.endpoint
        or os.environ.get("AZURE_FOUNDRY_ENDPOINT", "")
        or env_values.get("AZURE_FOUNDRY_ENDPOINT", "")
        or DEFAULT_ENDPOINT
    )
    account_name = args.account_name or infer_account_name(endpoint)

    print("EEOC Foundry Connect / OMP sync")
    print("----------------------------")
    print(f"endpoint:            {endpoint}")
    print(f"account:             {account_name}")

    ensure_login_and_subscription(args.subscription)
    validate_foundry_token()
    resource_group = discover_resource_group(account_name, args.resource_group)
    deployments = list_deployments(account_name, resource_group)
    print(f"active deployments:  {len(deployments)}")

    provider = build_provider(endpoint, deployments)
    document = merge_document(provider)

    # Remove only the legacy key this integration used. Preserve unrelated env vars.
    legacy_removed = env_values.pop("AZURE_OPENAI_API_KEY", None) is not None
    env_values["AZURE_FOUNDRY_ENDPOINT"] = endpoint

    if not args.dry_run:
        write_env_file(env_values)
        if legacy_removed:
            print(f"removed legacy key:  AZURE_OPENAI_API_KEY from {ENV_FILE}")
        print(f"env:                 {ENV_FILE}")

    write_models(document, dry_run=args.dry_run)

    print()
    if args.dry_run:
        print("Dry run complete; no files changed.")
    else:
        print(f"wrote provider:      {PROVIDER_ID}")
        print(f"models.yml:          {MODELS_YML}")
        print("authentication:      Entra ID via Azure CLI -> Authorization: Bearer")
        print()
        print("Next:")
        print("  1. Restart OMP")
        print("  2. Run: omp models find foundry")
        print("  3. Test a deployment, e.g.:")
        print("     omp --model foundry/<deployment> --no-session -p \"Reply with exactly: OK\"")
        print()
        print("Important: do not run an older API-key-based foundry-sync.py afterwards; it can overwrite models.yml.")


if __name__ == "__main__":
    main()
